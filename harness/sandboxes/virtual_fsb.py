import os
import stat
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from .. import exceptions

def human_size(size: int) -> str:
    value = float(size)

    for unit in ("B", "K", "M", "G", "T"):
        if value < 1024 or unit == "T":
            return f"{int(value)}B" if unit == "B" else f"{value:.1f}{unit}"
        value /= 1024

    raise AssertionError("Unreachable")

@dataclass(frozen=True)
class VirtualFileSystemSandbox:
    """
    This sandbox provides an isolated view of the filesystem based on the provided root path.
    It must **NOT** be used for file execution, code execution or anything that touches real OS.

    It's best suited only for reading, writing and creating files where we don't require the
    overhead of a real OS level sandbox.
    """

    root: Path
    can_read: bool = True
    can_write: bool = False
    can_execute: bool = False

    # with data classes __init__() is automatically generated by Python
    def __post_init__(self) -> None:
        root = self.root.expanduser().resolve(strict=True)

        if not root.is_dir():
            raise exceptions.NotADirectory(root)

        # setattr() calls this
        object.__setattr__(self, "root", root)

    def resolve(self, path: str) -> Path:
        """ Resolve path with respect to root. """
        
        relative = Path(path)

        if relative.is_absolute():
            raise exceptions.PermissionDenied("Absolute paths are not permitted")

        resolved = (self.root / relative).resolve(strict=True)

        if not resolved.is_relative_to(self.root):
            raise exceptions.PermissionDenied("Path escapes the workspace")

        return resolved

    def _permissions(self, path: Path, is_dir: bool) -> str:
        """ Constructs permission UNIX like strings: drwx, -rwx, -rw-, -r--, etc. """
        kind = "d" if is_dir else "-"

        readable = self.can_read and os.access(path, os.R_OK)
        writable = self.can_write and os.access(path, os.W_OK)

        # For dirs, x means traversal not execution
        executable = (
            (self.can_read if is_dir else self.can_execute)
            and os.access(path, os.X_OK)
        )

        return (
            kind
            + ("r" if readable else "-")
            + ("w" if writable else "-")
            + ("x" if executable else "-")
        )

    def list_directory(self, path: str = ".") -> str:
        """ Produce a compact, human-readable directory listing. """
        if not self.can_read:
            raise exceptions.PermissionDenied("Workspace reading is disabled.")

        directory = self.resolve(path)

        if not directory.is_dir():
            raise exceptions.NotADirectory(directory)

        if not os.access(directory, os.R_OK | os.X_OK):
            raise exceptions.PermissionDenied("Cannot list this directory.")

        lines: list[str] = []

        # sorted {pathobj.name: Path(...)}
        for entry in sorted(directory.iterdir(), key=lambda p: p.name):
            # WARNING: for now symlinks are not displayed
            if entry.is_symlink():
                continue

            info = entry.stat(follow_symlinks=False)
            is_dir = stat.S_ISDIR(info.st_mode)

            if not (is_dir or stat.S_ISREG(info.st_mode)):
                continue

            permissions = self._permissions(entry, is_dir)
            size = human_size(info.st_size)
            modified = datetime.fromtimestamp(info.st_mtime).strftime("%Y-%m-%d %H:%M")

            name = entry.name.replace("\n", "\\n")
            lines.append(f"{permissions} {size:>6} {modified} {name}")

        return "\n".join(lines)